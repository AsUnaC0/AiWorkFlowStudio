import { request } from "@/utils/request";

// ===========================================================================
// 桌宠客户端（desktop/，Electron）
// ===========================================================================

/**
 * 在本机拉起桌宠客户端。
 *
 * 浏览器沙箱不允许网页直接启动本地程序，所以由后端代劳 spawn。
 * 桌宠主进程有单实例锁：已经在跑时再调一次不会开出第二个，
 * 只会把已有窗口叫到前面 —— 语义上等价于「打开桌宠」。
 *
 * 前提是后端和用户在同一台机器上（本项目本地部署，成立）。
 * 后端在服务器上时接口会返回 503 并说明原因。
 */
export const launchDesktopPet = (): Promise<{ ok: boolean; message: string }> =>
  request.post("/desktop-pet/launch");
