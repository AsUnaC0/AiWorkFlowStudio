/** 判断某段人格文本是否是「已知的旧版文本」（可安全升级为当前默认值） */
export function isLegacyPersonaPrompt(text: string): boolean {
  const normalized = text.trim();
  if (!normalized) return false;
  return LEGACY_PERSONA_PROMPTS.some((p) => p.trim() === normalized);
}

